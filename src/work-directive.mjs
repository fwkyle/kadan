// 카드 없는 작업 지시 구분 (2026-09-15 card-kadan-send-no-card-guard).
// 감독이 카드 없이 본낸 실제 지시에서 관측된 명령 어미·일 동사만 쓴다 —
// 오늘 원장의 지시문은 `핑라`/`해라`/`여라`/`줘` 어미로 끝났다(리서치핑라·
// 실측핑라·추가해라·덧붙여라·답핑라). 애매한 형태는 넓게 잡지 않는다:
// '계속해'·'멈춰'·'뭐하고 있어' 같은 깨우기는 일 동사가 아니고,
// '확인했다' 같은 보고는 명령 어미가 아니라서 둘 다 걸리지 않는다.
const STEMS =
  "만들|고치|고쳐|수정|추가|구현|설계|작성|확인|조사|실측|리서치|구분|처리|분석|정리|교체|합치|합쳐|덧붙이|덧붙여|붙이|붙여|넣|빼|바꾸|바꿔|삭제|제거|남기|남겨|올리|올려|내리|내려|배포|적용|반영|재시작|재기동|읽|답|달|달아|쓰|써|띄우|띄워|실행|돌리|돌려|보내|본내";
const WORK_VERB = new RegExp(STEMS, "u");
// 강한 명령 어미는 뒤에 한글이 이어지지 않을 때만 명령으로 본다 —
// '확인해라고 했다'처럼 지시를 인용한 보고는 걸리지 않는다.
const IMPERATIVE_ENDING =
  /(?:해라|핑라|하라|하여라|하시오|으라|어라|아라|여라|거라|너라|해주세요|해주십시오|해주시오|해보세요|해봐|아봐|어봐|여봐|해줘|아줘|어줘|여줘|주세요|주십시오|세요|십시오|시오|자|줘|라)(?![가-힣])/u;
// '만들어'·'고쳐'처럼 어미 없이 끝나는 명령형은 줄 끝(또는 문장 부호 뒤 끝)에
// 있을 때만 본다 — '수정해 왔다'·'확인해?' 같은 서술·의문은 걸리지 않고,
// '이번 달'처럼 명사로 끝나는 말을 막기 위해 수렴형만 단독 인정한다.
const CONTRACTED = "고쳐|바꿔|합쳐|남겨|붙여|덧붙여|넣어|달아|올려|내려|읽어|써|띄워|돌려|보내|본내";
const SOFT_DIRECTIVE = new RegExp(
  `(?:${STEMS})(?:해|어|아|여|지)(?=[.!\\s]*$)|(?:${CONTRACTED})(?=[.!\\s]*$)`,
  "mu"
);

export function looksLikeWorkDirective(message) {
  if (typeof message !== "string") return false;
  return (
    (WORK_VERB.test(message) && IMPERATIVE_ENDING.test(message)) ||
    SOFT_DIRECTIVE.test(message)
  );
}
